// Writes site/js/status-render.js: the status view's renderer as a plain script the website's demo draws
// with, so the demo shows the frames the view draws instead of a port of them that falls behind.
//
//   pnpm site:renderer          write the copy
//
// The site has no build step and its scripts are plain (not modules, so the page also opens from disk).
// This strips the types from src/status-grid.ts and src/status-render.ts with Node's own type stripping and
// wraps them, with the few values they import from modules that need Node (the click hint's words, the
// usage bands, the TIME formats, the run's estimated end), in one function that sets
// `window.SandcastleRender`. The copy is committed; test/site-renderer-copy.test.ts fails when it differs from
// what this writes from src/ now. The deploy runs nothing.

import { readFileSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const KIT = fileURLToPath(new URL("..", import.meta.url));
export const OUTPUT = join(KIT, "site/js/status-render.js");

// The renderer's imports from modules that read files or start processes, as the declarations it uses and the
// ones those use. Taken from the source, never retyped here.
const EXTERNALS = {
  "click-hint.ts": ["HINT_TEXT"],
  "status-rows.ts": ["ago", "duration"],
  "status-snapshot.ts": ["isObject", "WORKING", "shownId", "runEnds"],
  "usage.ts": ["USAGE_AMBER", "USAGE_RED", "USAGE_STALE_SECONDS"],
};

// What the page gets: the renderer, its colours and the TIME format the demo's rows share with the table.
const EXPORTS = ["renderFrame", "palette", "ago"];

const strip = (file) => {
  // The warning says stripping is experimental; it is the ticket's chosen tool, and a script that writes a file should print nothing else.
  const emit = process.emitWarning;
  process.emitWarning = () => {};
  try {
    return stripTypeScriptTypes(readFileSync(join(KIT, "src", file), "utf8"), { mode: "strip" })
      .split("\n")
      .map((l) => l.trimEnd())
      .join("\n");
  } finally {
    process.emitWarning = emit;
  }
};

// A top-level declaration: its leading comment, and its lines up to the blank line or the next unindented line that is no closer.
const declaration = (source, name, file) => {
  const lines = source.split("\n");
  const at = lines.findIndex((l) => new RegExp(`^(?:export )?(?:const|function) ${name}\\b`).test(l));
  if (at < 0) throw new Error(`src/${file} has no top-level declaration of ${name}`);
  let end = at + 1;
  while (end < lines.length && lines[end] !== "" && /^([\s}\])]|;)/.test(lines[end])) end++;
  let start = at;
  while (start > 0 && /^(\/\/|\/\*\*| \*)/.test(lines[start - 1])) start--;
  return lines.slice(start, end).join("\n").replace(/^export /m, "");
};

// What a module imports as values (the stripped import statement keeps only those), by the module's file name.
const importedValues = (source) =>
  [...source.matchAll(/^import ([^;]*?) from "\.\/([^"]+)";$/gm)].map(([, names, file]) => [file, names.replace(/[{}]/g, " ").split(",").map((n) => n.trim()).filter(Boolean)]);

// The renderer's `import { junction as rule }` is no declaration once the import is gone.
const aliases = (source) =>
  importedValues(source)
    .flatMap(([, names]) => names)
    .flatMap((n) => (/^(\w+) as (\w+)$/.exec(n) ? [n.replace(/^(\w+) as (\w+)$/, "const $2 = $1;")] : []))
    .join("\n");

const body = (source) => source.replace(/^import [^;]*;$/gm, "").replace(/^export /gm, "").replace(/^\n+/, "").replace(/\n{3,}/g, "\n\n").trimEnd();

/** The text of site/js/status-render.js, as it stands from src/ now. */
export const siteRenderer = () => {
  const grid = strip("status-grid.ts");
  const render = strip("status-render.ts");
  for (const [file, names] of [...importedValues(grid), ...importedValues(render)]) {
    if (file === "status-grid.ts") continue;
    const known = EXTERNALS[file] ?? [];
    for (const name of names) if (!known.includes(name)) throw new Error(`src/status-render.ts imports ${name} from ${file}: add it to EXTERNALS in scripts/site-renderer.mjs`);
  }
  const externals = Object.entries(EXTERNALS).flatMap(([file, names]) => {
    const source = strip(file);
    return names.map((name) => declaration(source, name, file));
  });
  return `${[
    "// GENERATED by scripts/site-renderer.mjs (pnpm site:renderer) from src/status-grid.ts and src/status-render.ts: do not edit.",
    "// The status view's own renderer with its types stripped, so the page draws the frames the view draws.",
    "(function () {",
    "'use strict';",
    "",
    externals.join("\n\n"),
    "",
    body(grid),
    "",
    aliases(render),
    "",
    body(render),
    "",
    `window.SandcastleRender = { ${EXPORTS.join(", ")} };`,
    "})();",
  ].join("\n")}\n`;
};

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(OUTPUT, siteRenderer());
